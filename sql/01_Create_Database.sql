CREATE SCHEMA housing;

CREATE TABLE housing.town (
    town_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    town_name     text NOT NULL UNIQUE,
    CONSTRAINT town_name_canonical CHECK (
        town_name <> '' AND town_name = upper(btrim(town_name))
    )
);

CREATE TABLE housing.hdb_block (
    block_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    town_id       bigint NOT NULL REFERENCES housing.town(town_id)
                  ON UPDATE RESTRICT ON DELETE RESTRICT,
    block_no      text NOT NULL,
    street_name   text NOT NULL,
    latitude      double precision,
    longitude     double precision, 

    CONSTRAINT block_address_uk UNIQUE (block_no, street_name),
    CONSTRAINT block_no_canonical CHECK (
        block_no <> '' AND block_no = upper(btrim(block_no))
    ), 

    CONSTRAINT street_name_canonical CHECK (
        street_name <> '' AND street_name = upper(btrim(street_name))
    ), 

    CONSTRAINT block_coordinates_paired CHECK (
        (latitude IS NULL) = (longitude IS NULL)
    ), 

    CONSTRAINT block_latitude_valid CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT block_longitude_valid CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE housing.hdb_flat (
    flat_id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    block_id             bigint NOT NULL REFERENCES housing.hdb_block(block_id)
                         ON UPDATE RESTRICT ON DELETE RESTRICT,
    flat_type            text NOT NULL,
    flat_model           text NOT NULL,
    floor_area_sqm       numeric(8,2) NOT NULL,
    storey_lower         smallint NOT NULL,
    storey_upper         smallint NOT NULL,
    lease_commence_year  smallint NOT NULL, 

    CONSTRAINT flat_profile_uk UNIQUE (
        block_id, flat_type, flat_model, floor_area_sqm,
        storey_lower, storey_upper, lease_commence_year
    ), 

    CONSTRAINT flat_type_valid CHECK (flat_type IN (
        '1 ROOM', '2 ROOM', '3 ROOM', '4 ROOM', '5 ROOM',
        'EXECUTIVE', 'MULTI-GENERATION'
    )), 

    CONSTRAINT flat_model_canonical CHECK (
        flat_model <> '' AND flat_model = upper(btrim(flat_model))
    ), 

    CONSTRAINT floor_area_positive_finite CHECK (
        floor_area_sqm > 0 AND floor_area_sqm < 'Infinity'::numeric
    ), 

    CONSTRAINT storey_range_valid CHECK (
        storey_lower >= 1 AND storey_upper >= storey_lower
    ), 

    CONSTRAINT lease_year_valid CHECK (lease_commence_year BETWEEN 1900 AND 9999)
);

COMMENT ON TABLE housing.hdb_flat IS
'An observed flat-attribute profile, not an identified physical unit. Multiple units may share one profile.';

CREATE TABLE housing.source_file (
    source_file_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name        text NOT NULL,
    sha256           text NOT NULL UNIQUE,
    date_basis       text NOT NULL, 

    CONSTRAINT source_filename_nonblank CHECK (
        file_name <> '' AND file_name = btrim(file_name)
    ), 

    CONSTRAINT source_sha256_valid CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT source_date_basis_valid CHECK (
        date_basis IN ('APPROVAL', 'REGISTRATION')
    )
);

CREATE TABLE housing.resale_transaction (
    transaction_id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flat_id                         bigint NOT NULL REFERENCES housing.hdb_flat(flat_id)
                                    ON UPDATE RESTRICT ON DELETE RESTRICT,
    source_file_id                  bigint NOT NULL REFERENCES housing.source_file(source_file_id)
                                    ON UPDATE RESTRICT ON DELETE RESTRICT,
    source_row_number               bigint NOT NULL,
    transaction_month               date NOT NULL,
    resale_price                    numeric(12,2) NOT NULL,
    remaining_lease_months_reported  smallint,
    remaining_lease_precision       text, 

    CONSTRAINT source_row_uk UNIQUE (source_file_id, source_row_number),
    CONSTRAINT source_row_positive CHECK (source_row_number >= 1), 

    CONSTRAINT transaction_month_valid CHECK (
        transaction_month >= DATE '1900-01-01'
        AND transaction_month < DATE '10000-01-01'
        AND EXTRACT(DAY FROM transaction_month) = 1
    ), 

    CONSTRAINT resale_price_positive_finite CHECK (
        resale_price > 0 AND resale_price < 'Infinity'::numeric
    ), 

    CONSTRAINT reported_lease_range CHECK (
        remaining_lease_months_reported BETWEEN 0 AND 1188
    ), 

    CONSTRAINT reported_lease_precision_valid CHECK (
        remaining_lease_precision IN ('MONTH', 'YEAR')
    ), 

    CONSTRAINT reported_lease_fields_paired CHECK (
        (remaining_lease_months_reported IS NULL)
        = (remaining_lease_precision IS NULL)
    ), 

    CONSTRAINT reported_years_are_whole CHECK (
        remaining_lease_precision IS DISTINCT FROM 'YEAR'
        OR remaining_lease_months_reported % 12 = 0
    )
);

COMMENT ON COLUMN housing.resale_transaction.transaction_month IS
'First day encodes a source month, not the exact day of sale. Meaning is given by source_file.date_basis.';

COMMENT ON COLUMN housing.resale_transaction.source_row_number IS
'1-based data record number in the immutable source file, excluding its header.';

CREATE TABLE housing.hawker_centre (
    hawker_id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    centre_name           text NOT NULL UNIQUE,
    address               text NOT NULL,
    centre_type           text NOT NULL,
    cooked_food_stalls    integer NOT NULL,
    market_produce_stalls integer NOT NULL,
    latitude              double precision,
    longitude             double precision,

    CONSTRAINT centre_name_canonical CHECK (
        centre_name <> '' AND centre_name = upper(btrim(centre_name))
    ),

    CONSTRAINT centre_address_nonblank CHECK (
        address <> '' AND address = btrim(address)
    ),

    CONSTRAINT centre_type_valid CHECK (centre_type IN ('HC', 'MHC', 'MK')),
    CONSTRAINT cooked_stalls_nonnegative CHECK (cooked_food_stalls >= 0),

    CONSTRAINT market_stalls_nonnegative CHECK (market_produce_stalls >= 0),
    CONSTRAINT hawker_coordinates_paired CHECK (
        (latitude IS NULL) = (longitude IS NULL)
    ),

    CONSTRAINT hawker_latitude_valid CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT hawker_longitude_valid CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE housing.block_hawker_distance (
    block_id     bigint NOT NULL REFERENCES housing.hdb_block(block_id)
                 ON UPDATE RESTRICT ON DELETE RESTRICT,
    hawker_id    bigint NOT NULL REFERENCES housing.hawker_centre(hawker_id)
                 ON UPDATE RESTRICT ON DELETE RESTRICT,
    distance_m   double precision NOT NULL,

    PRIMARY KEY (block_id, hawker_id),
    -- pi * 6,371,000 metres is the maximum great-circle distance.
    -- The slightly larger bound also rejects Infinity and NaN.
    CONSTRAINT distance_valid CHECK (distance_m BETWEEN 0 AND 20040000)

);

COMMENT ON TABLE housing.block_hawker_distance IS
'One Haversine distance per geocoded block-centre pair. ETL must validate coordinates, coverage and recomputation after coordinate changes.';

CREATE FUNCTION housing.proximity_class(distance_m double precision)
RETURNS text
LANGUAGE sql
IMMUTABLE
STRICT
PARALLEL SAFE

AS $function$
    SELECT CASE
        WHEN distance_m >= 0 AND distance_m < 500 THEN 'NEAR'
        WHEN distance_m >= 500 AND distance_m < 1000 THEN 'MEDIUM'
        WHEN distance_m >= 1000 AND distance_m <= 20040000 THEN 'FAR'
        ELSE NULL
    END;
$function$;

-- Distance determines class, so class is derived rather than duplicated
-- as a non-key stored attribute in block_hawker_distance.
CREATE VIEW housing.v_block_hawker_proximity AS
SELECT block_id, hawker_id, distance_m,
       housing.proximity_class(distance_m) AS proximity_class
FROM housing.block_hawker_distance;

-- Q4: exactly one eligible nearest centre per block with distance data.
-- MK means market-only and is not in the eligible hawker population.
CREATE VIEW housing.v_nearest_hawker AS
SELECT block_id, hawker_id, distance_m,
       housing.proximity_class(distance_m) AS proximity_class
FROM (
    SELECT d.*,
           ROW_NUMBER() OVER (
               PARTITION BY d.block_id ORDER BY d.distance_m, d.hawker_id
           ) AS nearest_rank
    FROM housing.block_hawker_distance AS d
    JOIN housing.hawker_centre AS h USING (hawker_id)
    WHERE h.centre_type IN ('HC', 'MHC')
) AS ranked
WHERE nearest_rank = 1;

-- Q5: filter to fresh-market hawkers BEFORE selecting the nearest one.
CREATE VIEW housing.v_nearest_market_hawker AS
SELECT block_id, hawker_id, distance_m,
       housing.proximity_class(distance_m) AS proximity_class
FROM (
    SELECT d.*,
           ROW_NUMBER() OVER (
               PARTITION BY d.block_id ORDER BY d.distance_m, d.hawker_id
           ) AS nearest_rank
    FROM housing.block_hawker_distance AS d
    JOIN housing.hawker_centre AS h USING (hawker_id)
    WHERE h.centre_type IN ('HC', 'MHC')
      AND h.market_produce_stalls > 0
) AS ranked
WHERE nearest_rank = 1;

-- Q1-Q3 support: one row per sale. Values derived across tables are views,
-- not generated columns that would need to reference another table.
CREATE VIEW housing.v_resale_analysis AS
SELECT r.transaction_id, r.source_file_id, r.source_row_number,
       r.flat_id, f.block_id, b.town_id, t.town_name,
       f.flat_type, f.flat_model, f.floor_area_sqm,
       f.storey_lower, f.storey_upper, f.lease_commence_year,
       r.transaction_month,
       EXTRACT(YEAR FROM r.transaction_month)::integer AS transaction_year,
       r.resale_price,
       r.resale_price / f.floor_area_sqm AS price_per_sqm,
       r.remaining_lease_months_reported,
       r.remaining_lease_precision,

       CASE
           WHEN r.remaining_lease_months_reported IS NOT NULL
               THEN r.remaining_lease_months_reported::integer
           WHEN estimate.months BETWEEN 0 AND 1188 THEN estimate.months
           ELSE NULL
       END AS remaining_lease_months,

       CASE
           WHEN r.remaining_lease_precision = 'MONTH' THEN 'REPORTED_MONTH'
           WHEN r.remaining_lease_precision = 'YEAR' THEN 'REPORTED_YEAR'
           WHEN estimate.months BETWEEN 0 AND 1188 THEN 'ESTIMATED_YEAR'
           ELSE 'UNAVAILABLE'
       END AS remaining_lease_basis

FROM housing.resale_transaction AS r
JOIN housing.hdb_flat AS f USING (flat_id)
JOIN housing.hdb_block AS b USING (block_id)
JOIN housing.town AS t USING (town_id)

CROSS JOIN LATERAL (
    SELECT (99 - (
        EXTRACT(YEAR FROM r.transaction_month)::integer - f.lease_commence_year
    )) * 12 AS months
) AS estimate;

-- Only key/uniqueness indexes are created automatically here.
-- Leave optional performance indexes for Task 4.
COMMIT;
